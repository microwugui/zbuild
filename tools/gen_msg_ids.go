package main

// src/internal/logger/msg_ids.ts 与 testdata/msgids.json 的生成器（本轮已跑过；保留下来供复现）。
//
// 用法：在 esbuild 仓库（/root/esbuild，v0.28.2 f6058f83）里建子目录并运行：
//   mkdir -p tmpmsgidgen && cp tools/gen_msg_ids.go tmpmsgidgen/main.go
//   go run ./tmpmsgidgen      → /tmp/msg_ids.ts + /tmp/msgids.json
//
// 生成物入库后不手改；测试用 sha256 钉住 testdata/msgids.json。

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"strings"

	"github.com/evanw/esbuild/internal/logger"
)

type idRow struct {
	name  string
	value int
	str   string
}

func main() {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "/root/esbuild/internal/logger/msg_ids.go", nil, 0)
	if err != nil {
		panic(err)
	}

	var rows []idRow
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		var names []string
		for _, s := range gd.Specs {
			vs := s.(*ast.ValueSpec)
			for _, n := range vs.Names {
				if strings.HasPrefix(n.Name, "MsgID_") {
					names = append(names, n.Name)
				}
			}
		}
		if len(names) == 0 || names[0] != "MsgID_None" {
			continue
		}
		for i, n := range names {
			rows = append(rows, idRow{name: n, value: i})
		}
	}
	if len(rows) == 0 {
		panic("no MsgID const block")
	}

	// 校验：块内常量个数必须等于 MsgID_END+1，且每个 ID 的 name 用包导出函数回读
	if got, want := len(rows), int(logger.MsgID_END)+1; got != want {
		panic(fmt.Sprintf("count mismatch: %d vs MsgID_END+1=%d", got, want))
	}
	for i := range rows {
		if rows[i].value != i {
			panic("iota order mismatch")
		}
		rows[i].str = logger.MsgIDToString(logger.MsgID(i))
	}

	// StringToMsgIDs 的 case 表：从源码 switch 抽取 (str, MsgID名)
	type pair struct{ str, id string }
	var pairs []pair
	var pkgFirst, pkgLast, tsFirst, tsLast int = -1, -1, -1, -1
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Name.Name != "StringToMsgIDs" {
			continue
		}
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			cc, ok := n.(*ast.CaseClause)
			if !ok {
				return true
			}
			var strLit string
			if len(cc.List) == 1 {
				bl, ok := cc.List[0].(*ast.BasicLit)
				if ok && bl.Kind == token.STRING {
					strLit = strings.Trim(bl.Value, "\"")
				}
			}
			for _, st := range cc.Body {
				// overrides[MsgID_X] = logLevel
				if as, ok := st.(*ast.AssignStmt); ok && len(as.Lhs) == 1 {
					if ix, ok := as.Lhs[0].(*ast.IndexExpr); ok {
						if id, ok := ix.Index.(*ast.Ident); ok && strLit != "" {
							pairs = append(pairs, pair{strLit, id.Name})
						}
					}
				}
				// for i := MsgID_X_FIRST; i <= MsgID_X_LAST; i++ { overrides[i] = logLevel }
				if fr, ok := st.(*ast.ForStmt); ok {
					if as, ok := fr.Init.(*ast.AssignStmt); ok && len(as.Rhs) == 1 {
						if id, ok := as.Rhs[0].(*ast.Ident); ok {
							switch {
							case id.Name == "MsgID_PackageJSON_FIRST":
								pkgFirst = int(logger.MsgID_PackageJSON_FIRST)
								pkgLast = int(logger.MsgID_PackageJSON_LAST)
							case id.Name == "MsgID_TSConfigJSON_FIRST":
								tsFirst = int(logger.MsgID_TSConfigJSON_FIRST)
								tsLast = int(logger.MsgID_TSConfigJSON_LAST)
							}
						}
					}
				}
			}
			return true
		})
	}
	if pkgFirst < 0 || tsFirst < 0 {
		panic("ranges not found")
	}

	var sb strings.Builder
	sb.WriteString("// AUTO-GENERATED by tools/gen_msg_ids.go（生成器已保留；若手改请同步生成器）。请勿手改。\n")
	sb.WriteString("// 源: esbuild internal/logger/msg_ids.go（v0.28.2 f6058f83）。\n")
	sb.WriteString("// 生成时校验：常量块条目数 == MsgID_END+1；每个 ID 的 str 由 Go 的 logger.MsgIDToString 回读。\n")
	sb.WriteString("//\n")
	sb.WriteString("// DEVIATION: Go 的 msgIDInfo 带 vsID（visualstudio style 用），本轮未落 visualstudio style，\n")
	sb.WriteString("// 故 msgIDToInfo 只返回 name。补 style_visualstudio.go 时把 vsID 一并生成进来。\n\n")
	sb.WriteString("import { LogLevel } from \"./logger.ts\";\n\n")
	sb.WriteString("export type MsgID = number;\n\n")
	for _, r := range rows {
		fmt.Fprintf(&sb, "export const %s = %d;\n", r.name, r.value)
	}
	sb.WriteString("\n/** Go: msgIDInfo */\nexport interface MsgIDInfo {\n  name: string;\n}\n\n")
	sb.WriteString("// Go: msgIDToInfo 的 switch → 直接表（内容取自 Go 回读，含 package.json/tsconfig.json 折叠）\n")
	sb.WriteString("const msgIDNames: (string | null)[] = [\n")
	for _, r := range rows {
		fmt.Fprintf(&sb, "  %q,\n", r.str)
	}
	sb.WriteString("];\n\n")
	sb.WriteString("export function msgIDToInfo(id: MsgID): MsgIDInfo {\n")
	sb.WriteString("  const name = msgIDNames[id];\n")
	sb.WriteString("  return { name: name === undefined || name === null ? \"\" : name };\n")
	sb.WriteString("}\n\n")
	sb.WriteString("/** Go: func MsgIDToString(id MsgID) string */\n")
	sb.WriteString("export function MsgIDToString(id: MsgID): string {\n  return msgIDToInfo(id).name;\n}\n\n")
	sb.WriteString("// Go: StringToMsgIDs 的 switch → (外部名字, ID) 表；package.json/tsconfig.json 是区间赋值\n")
	sb.WriteString("const msgIDStringToID: [string, MsgID][] = [\n")
	for _, p := range pairs {
		fmt.Fprintf(&sb, "  [%q, %s],\n", p.str, p.id)
	}
	sb.WriteString("];\n\n")
	sb.WriteString("const msgIDRanges: [\n  string,\n  MsgID,\n  MsgID,\n][] = [\n")
	fmt.Fprintf(&sb, "  [\"package.json\", %d, %d],\n", pkgFirst, pkgLast)
	fmt.Fprintf(&sb, "  [\"tsconfig.json\", %d, %d],\n", tsFirst, tsLast)
	sb.WriteString("];\n\n")
	sb.WriteString("/** Go: func StringToMsgIDs(str string, logLevel LogLevel, overrides map[MsgID]LogLevel) */\n")
	sb.WriteString("export function StringToMsgIDs(str: string, logLevel: LogLevel, overrides: Map<MsgID, LogLevel>): void {\n")
	sb.WriteString("  for (const [name, id] of msgIDStringToID) {\n")
	sb.WriteString("    if (name === str) {\n      overrides.set(id, logLevel);\n      return;\n    }\n  }\n")
	sb.WriteString("  for (const [name, first, last] of msgIDRanges) {\n")
	sb.WriteString("    if (name === str) {\n      for (let i = first; i <= last; i++) overrides.set(i, logLevel);\n      return;\n    }\n  }\n")
	sb.WriteString("  // 无效条目一律忽略：消息 ID 可能在代码写完之后被改名/删除\n}\n\n")
	sb.WriteString("/** Go: func StringToMaximumMsgID(id string) MsgID */\n")
	sb.WriteString("export function StringToMaximumMsgID(id: string): MsgID {\n")
	sb.WriteString("  const overrides = new Map<MsgID, LogLevel>();\n")
	sb.WriteString("  let maxID: MsgID = MsgID_None;\n")
	sb.WriteString("  StringToMsgIDs(id, LogLevel.Info, overrides);\n")
	sb.WriteString("  for (const k of overrides.keys()) if (k > maxID) maxID = k;\n")
	sb.WriteString("  return maxID;\n}\n")

	if err := os.WriteFile("/tmp/msg_ids.ts", []byte(sb.String()), 0644); err != nil {
		panic(err)
	}
	// 供 TS 测试逐条比对的期望值（等价于「每个 ID 在 Go 侧回读」）
	var js strings.Builder
	js.WriteString("{\n \"ids\": [\n")
	for i, r := range rows {
		comma := ","
		if i == len(rows)-1 {
			comma = ""
		}
		fmt.Fprintf(&js, "  {\"name\": %q, \"value\": %d, \"str\": %q}%s\n", r.name, r.value, r.str, comma)
	}
	js.WriteString(" ],\n \"pairs\": [\n")
	for i, p := range pairs {
		comma := ","
		if i == len(pairs)-1 {
			comma = ""
		}
		fmt.Fprintf(&js, "  {\"str\": %q, \"id\": %q}%s\n", p.str, p.id, comma)
	}
	js.WriteString(" ],\n \"ranges\": [\n")
	fmt.Fprintf(&js, "  {\"str\": \"package.json\", \"first\": %d, \"last\": %d},\n", pkgFirst, pkgLast)
	fmt.Fprintf(&js, "  {\"str\": \"tsconfig.json\", \"first\": %d, \"last\": %d}\n", tsFirst, tsLast)
	js.WriteString(" ]\n}\n")
	if err := os.WriteFile("/tmp/msgids.json", []byte(js.String()), 0644); err != nil {
		panic(err)
	}

	fmt.Printf("rows=%d pairs=%d pkg=%d..%d ts=%d..%d\n", len(rows), len(pairs), pkgFirst, pkgLast, tsFirst, tsLast)
}
