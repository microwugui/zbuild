/**
 * Go: func unicode.Is(rangeTab *RangeTable, r rune) bool
 *
 * 表按 Lo 升序（R16 在前、R32 在后），所以「r < Lo 即停」与 Go 的二分/线性扫描等价：
 * Stride 为 1 时区间连续，否则只命中 (r-Lo)%Stride==0 的点。
 */
export function isInRangeTable(table: Int32Array, r: number): boolean {
  for (let i = 0; i < table.length; i += 3) {
    const lo = table[i], hi = table[i + 1], stride = table[i + 2];
    if (r < lo) return false;
    if (r <= hi && (stride === 1 || (r - lo) % stride === 0)) return true;
  }
  return false;
}

