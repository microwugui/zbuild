const bytes = new Uint8Array(readFileSync(new URL("../../../testdata/graph-base-go.json", import.meta.url)));
const SHA = "aed1e7b29b36f0ae5134f8e18316c81048ef823c88d158dd009f843065237bd4";
const canon = (x: any): any => Array.isArray(x) ? x.map(canon) : (x && typeof x === "object" ? Object.fromEntries(Object.keys(x).sort().map((k) => [k, canon(x[k])])) : x);
const ref = (s: number, i: number) => new ast.Ref(s, i);
const rk = (r: ast.Ref) => `${r.SourceIndex}:${r.InnerIndex}`;

function makeInput(srcIdx: number, symNames: string[], exportNames: string[], partCount: number, src: string, importCount: number): InputFile {
  const f = new InputFile();
  const repr = new JSRepr();
  repr.AST.Symbols = symNames.map((n) => { const s = new ast.Symbol(); s.OriginalName = n; s.Link = ast.InvalidRef; return s; });
  for (const n of exportNames) {
    const ne = new js_ast.NamedExport(); ne.Ref = ref(srcIdx, 0);
    repr.AST.NamedExports.set(n, ne);
    repr.AST.TopLevelSymbolToPartsFromParser.set(rk(ref(srcIdx, 0)), [0]);
  }
  for (let i = 0; i < partCount; i++) { const p = new js_ast.Part(); p.SymbolUses = new Map(); repr.AST.Parts.push(p); }
  for (let i = 0; i < importCount; i++) repr.AST.ImportRecords.push({ Kind: 1, SourceIndex: undefined } as any);
  repr.AST.ModuleScope = new js_ast.Scope();
  repr.AST.ExportsRef = ref(srcIdx, 0); repr.AST.ModuleRef = ref(srcIdx, 0);
  const s = new Source(); s.Contents = new TextEncoder().encode(src); f.Source = s;
  f.Repr = repr;
  return f;
}
const dumpRef = (r: ast.Ref): any => [r.SourceIndex, r.InnerIndex];
function dumpGraph(g: LinkerGraph): any {
  const files = g.Files.map((f) => {
    const bits: number[] = [];
    for (let b = 0; b < g.entryPoints.length + 2; b++) if (b / 8 < f.EntryBits.entries.length && ((f.EntryBits.entries[Math.floor(b / 8)] >> (b & 7)) & 1) !== 0) bits.push(b);
    return { kind: f.entryPointKind, dist: f.DistanceFromEntryPoint, epChunk: f.EntryPointChunkIndex, isLive: f.IsLive, bits };
  });
  const eps = g.EntryPoints().map((e) => [e.OutputPath, e.SourceIndex, e.OutputPathWasAutoGenerated]);
  const symCounts = g.Symbols.SymbolsForSource.map((s) => s ? s.length : 0);
  return { files, entryPoints: eps, symCounts, reachable: g.ReachableFiles, stable: g.StableSourceIndices };
}
function dumpRepr(g: LinkerGraph, sourceIndex: number): any {
  const repr = g.Files[sourceIndex].InputFile.Repr as JSRepr;
  const parts = repr.AST.Parts.map((p) => {
    const uses: number[] = []; for (const u of p.SymbolUses.values()) uses.push(u.CountEstimate);
    const deps: any[] = p.Dependencies.map((d) => [d.SourceIndex, d.PartIndex]);
    return { uses, deps, decl: p.DeclaredSymbols.length };
  });
  const generated = repr.AST.ModuleScope!.Generated.map(dumpRef);
  const importsToBind: any[] = []; for (const d of repr.Meta.ImportsToBind.values()) importsToBind.push([d.SourceIndex, dumpRef(d.Ref)]);
  const overlay: any[] = []; for (const v of repr.Meta.TopLevelSymbolToPartsOverlay.values()) overlay.push(v);
  return { parts, generated, importsToBind, overlay, nImportRecords: repr.AST.ImportRecords.length, resolvedExports: repr.Meta.ResolvedExports.size };
}
const mkInputs = (): InputFile[] => [
  makeInput(0, ["__commonJS", "__esm", "__commonJSMin", "__esmMin"], [], 1, "runtime", 0),
  makeInput(1, ["a", "b"], ["foo", "bar"], 2, "a source", 1),
  makeInput(2, ["c"], ["baz"], 1, "b source", 0),
];
const mkEps = (): EntryPoint[] => { const e = new EntryPoint(); e.OutputPath = "a.js"; e.SourceIndex = 1; e.OutputPathWasAutoGenerated = true; return [e]; };

test("graph-base fixture sha256 + 10 例逐字节等于 Go", () => {
  assert.equal(createHash("sha256").update(bytes).digest("hex"), SHA);
  const rows: any[] = JSON.parse(new TextDecoder().decode(bytes));
  for (const r of rows) {
    const a = r.arg; let got: any;
    const inputs = mkInputs(), reachable = [0, 1, 2], eps = mkEps();
    if (r.fn === "CloneLinkerGraph") {
      const g = CloneLinkerGraph(inputs, reachable, eps, a.codeSplit);
      got = dumpGraph(g);
    } else if (r.fn === "CloneLinkerGraph.antiAlias") {
      const before = (inputs[1].Repr as JSRepr).AST.Symbols.length;
      const g = CloneLinkerGraph(inputs, reachable, eps, false);
      g.GenerateNewSymbol(1, 0, "x");
      (g.Files[1].InputFile.Repr as JSRepr).Meta.ResolvedExports.set("NEW", new ExportData());
      const after = (inputs[1].Repr as JSRepr).AST.Symbols.length;
      const origMeta = (inputs[1].Repr as JSRepr).Meta.ResolvedExports.size;
      got = [before === after, origMeta];
    } else if (r.fn === "CloneLinkerGraph.repr1") {
      const g = CloneLinkerGraph(inputs, reachable, eps, a.codeSplit);
      got = dumpRepr(g, 1);
    } else if (r.fn === "GenerateNewSymbol") {
      const g = CloneLinkerGraph(inputs, reachable, eps, false);
      const rr = g.GenerateNewSymbol(1, a.kind, a.name);
      got = { ref: dumpRef(rr), repr: dumpRepr(g, 1), symCount: (g.Symbols.SymbolsForSource[1] as ast.Symbol[]).length };
    } else if (r.fn === "AddPartToFile") {
      const g = CloneLinkerGraph(inputs, reachable, eps, false);
      g.GenerateNewSymbol(1, 0, "generated"); // Go 探针在同一 g 上先调了 GenerateNewSymbol
      const p = new js_ast.Part(); p.DeclaredSymbols = [new js_ast.DeclaredSymbol()]; p.DeclaredSymbols[0].Ref = ref(1, 0); p.DeclaredSymbols[0].IsTopLevel = true;
      const su = new js_ast.SymbolUse(); su.CountEstimate = 2; p.SymbolUses.set(rk(ref(1, 1)), su);
      const pi = g.AddPartToFile(1, p);
      got = { partIndex: pi, repr: dumpRepr(g, 1) };
    } else if (r.fn === "GenerateSymbolImportAndUse" || r.fn === "GenerateSymbolImportAndUse.zero") {
      const g = CloneLinkerGraph(inputs, reachable, eps, false);
      const p = new js_ast.Part();
      if (r.fn === "GenerateSymbolImportAndUse") { p.DeclaredSymbols = [new js_ast.DeclaredSymbol()]; p.DeclaredSymbols[0].Ref = ref(1, 0); p.DeclaredSymbols[0].IsTopLevel = true; }
      p.SymbolUses = new Map();
      const pi = g.AddPartToFile(1, p);
      g.GenerateSymbolImportAndUse(1, pi, ref(2, 0), a.useCount, 2);
      got = dumpRepr(g, 1);
    } else if (r.fn === "GenerateRuntimeSymbolImportAndUse") {
      const g = CloneLinkerGraph(inputs, reachable, eps, false);
      const p = new js_ast.Part(); p.SymbolUses = new Map();
      const pi = g.AddPartToFile(1, p);
      g.GenerateRuntimeSymbolImportAndUse(1, pi, a.name, a.useCount);
      got = dumpRepr(g, 1);
    } else if (r.fn === "TopLevelSymbolToParts.parser") {
      const repr = inputs[1].Repr as JSRepr;
      got = repr.TopLevelSymbolToParts(ref(1, 0));
    } else if (r.fn === "LineColumnTracker") {
      const g = CloneLinkerGraph(inputs, reachable, eps, false);
      const f = g.Files[1];
      const tracker = f.LineColumnTracker();
      const md = tracker.MsgData({ Loc: { Start: 0 }, Len: 1 } as any, "x");
      got = [md.Location.Line, md.Location.Column, f.LineColumnTracker() === tracker];
    } else if (r.fn === "JSRepr.ImportRecords") {
      const jr = new JSRepr(); jr.AST.ImportRecords = [{ Kind: 1 } as any, { Kind: 3 } as any];
      got = jr.ImportRecords().length;
    } else if (r.fn === "CSSRepr.ImportRecords") {
      const cr = new CSSRepr(); (cr.AST as any).ImportRecords = [{ Kind: 8 } as any];
      got = cr.ImportRecords().length;
    } else if (r.fn === "CopyRepr.ImportRecords") {
      got = new CopyRepr().ImportRecords() === null;
    } else throw new Error("unknown " + r.fn);
    assert.equal(JSON.stringify(canon(got)), JSON.stringify(canon(r.out)), `${r.fn} ${JSON.stringify(a)} => ${JSON.stringify(got)} != ${JSON.stringify(r.out)}`);
  }
  assert.equal(rows.length, 15);
});
