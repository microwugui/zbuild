// 第 116 轮：addEntryPoints 确定性 phase-2 逐字节等于 Go（注入 resolve/parse，4 场景）。
// Go 探针 tools/go/tmpgen_entrypoints_test.go 已交叉验证 helper 与真实 addEntryPoints 输出一致。
// Go 期望：testdata/entrypoints-go.json（SHA 726b9398…）。
import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { addEntryPoints } from "./bundler.ts";
import { MockFS, MockUnix } from "../fs/fs_mock.ts";

const raw = new Uint8Array(readFileSync(new URL("../../../testdata/entrypoints-go.json", import.meta.url)));
const SHA = "726b9398032192fab22f662ffd0a66898e0dd492f274c063e01c8e480435c709";
const rows = JSON.parse(new TextDecoder().decode(raw)) as any[];

type TC = {
  name: string; files: Record<string, string>;
  entries: { InputPath: string; OutputPath: string }[];
  absOutDir: string;
};
const cases: TC[] = [
  { name: "relative", files: { "/p/src/a.js": "var a=1;", "/p/src/b.js": "var b=2;" },
    entries: [{ InputPath: "./src/a.js", OutputPath: "" }, { InputPath: "./src/b.js", OutputPath: "" }], absOutDir: "/p/out" },
  { name: "explicit-output", files: { "/p/src/a.js": "var a=1;" },
    entries: [{ InputPath: "./src/a.js", OutputPath: "custom" }], absOutDir: "/p/out" },
  { name: "package-path", files: { "/p/foo.js": "var f=1;" },
    entries: [{ InputPath: "foo", OutputPath: "" }], absOutDir: "/p/out" },
  { name: "one-file", files: { "/p/index.js": "var x=1;" },
    entries: [{ InputPath: "index.js", OutputPath: "" }], absOutDir: "/p/out" },
];

function run(tc: TC): any[] {
  const fsObj = MockFS(tc.files, MockUnix, "/p");
  const s: any = { fs: fsObj, options: { AbsOutputDir: tc.absOutDir, AbsOutputBase: "" } };
  // injected resolve: package path "foo" unresolved -> [] (mirrors Go probe); others -> abs path
  const infos: (string | null)[][] = tc.entries.map((e) => {
    if (e.InputPath === "foo") return [];
    const abs = fsObj.IsAbs(e.InputPath) ? e.InputPath : fsObj.Join(["/p", e.InputPath]);
    return [abs];
  });
  const idxByPath = new Map<string, number>();
  tc.entries.forEach((e, i) => {
    const abs = fsObj.IsAbs(e.InputPath) ? e.InputPath : fsObj.Join(["/p", e.InputPath]);
    idxByPath.set(abs, i + 1);
  });
  const metas = addEntryPoints(s, tc.entries, infos, (abs) => idxByPath.get(abs) ?? 0);
  return metas.map((m) => ({ name: tc.name, outputPath: m.OutputPath, sourceIndex: m.SourceIndex, auto: m.OutputPathWasAutoGenerated }));
}

test("entrypoints 夹具 sha256（4 场景）", () => {
  assert.equal(createHash("sha256").update(raw).digest("hex"), SHA);
});

test("addEntryPoints phase-2 逐字节等于 Go", () => {
  const expected: any[] = [];
  for (const tc of cases) expected.push(...run(tc));
  assert.deepEqual(expected, rows);
});
