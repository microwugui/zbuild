// 第 87 轮：sanitizeLocation / lowestCommonAncestorDirectory 共享 Go 探针（11 例）。
import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { MockFS } from "../fs/fs_mock.ts";
import { sanitizeLocation, lowestCommonAncestorDirectory } from "./bundler.ts";

const raw = new Uint8Array(readFileSync(new URL("../../../testdata/bundler-light-go.json", import.meta.url)));
const SHA = "2c728085f9053e6eba286dc4ac6cf5a499089277c449d578b3751312dd48f451";
const fx = JSON.parse(new TextDecoder().decode(raw)) as { rows: { name: string; out: string }[] };
const by = Object.fromEntries(fx.rows.map((r) => [r.name, r.out]));
const lca: Record<string, [string[], boolean[]]> = {
  empty: [[], []],
  "explicit-only": [["/a/b/c.js"], [false]],
  "one-auto": [["/a/b/c.js"], [true]],
  "two-auto": [["/a/b/c.js", "/a/b/d.js"], [true, true]],
  divergent: [["/a/b/c.js", "/x/y/z.js"], [true, true]],
  prefix: [["/a/b/c.js", "/a/bb/d.js"], [true, true]],
  mixed: [["/a/b/c.js", "/a/d/e.js"], [true, false]],
};
const san: Record<string, { ns: string; abs: string }> = {
  "nil-loc": { ns: "", abs: "" }, "empty-ns": { ns: "", abs: "/a/b.js" },
  "with-ns": { ns: "file", abs: "/a/b.js" }, "empty-path": { ns: "", abs: "" },
};

test("bundler-light 夹具 sha256", () => {
  assert.equal(createHash("sha256").update(raw).digest("hex"), SHA);
});

test("lowestCommonAncestorDirectory 逐字节等于 Go（7 例）", () => {
  const fsObj = MockFS({}, 0, "/home/user/project");
  for (const [name, [paths, auto]] of Object.entries(lca)) {
    const eps = paths.map((p, i) => ({ OutputPath: p, OutputPathWasAutoGenerated: auto[i] }));
    assert.equal(lowestCommonAncestorDirectory(fsObj, eps), by["lca:" + name], "lca:" + name);
  }
});

test("sanitizeLocation 逐字节等于 Go（4 例）", () => {
  const fsObj = MockFS({}, 0, "/home/user/project");
  assert.equal(sanitizeLocation(fsObj, null) === undefined ? "nil" : "bad", by["san:nil-loc"]);
  for (const [name, c] of Object.entries(san)) {
    if (name === "nil-loc") continue;
    const loc: any = { Namespace: c.ns, File: { Abs: c.abs, Rel: "" } };
    sanitizeLocation(fsObj, loc);
    const out = JSON.stringify({ abs: loc.File.Abs, ns: loc.Namespace, rel: loc.File.Rel });
    assert.equal(out, by["san:" + name], "san:" + name);
  }
});
