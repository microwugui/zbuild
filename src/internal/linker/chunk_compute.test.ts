function mkCond(layer: string | undefined): css_ast.ImportConditions | null {
  if (!layer) return null;
  const c = new css_ast.ImportConditions();
  const t = new css_ast.Token(); t.Kind = 29; t.Text = layer;
  c.Layers = [t];
  return c;
}
interface ImportSpec { source: number; path?: string; kind: number; conditions?: string; }
interface CSSRuleSpec { recIdx: number; conditions?: string; }
interface PartSpec { deps?: [number, number][]; removable?: boolean; forceTree?: boolean; importRecs?: number[]; }
interface FileSpec { kind: string; path: string; cssSource?: number; parts?: PartSpec[]; imports?: ImportSpec[];
  sideEffects?: number; layersPre?: string[][]; layersPost?: string[][]; cssRules?: CSSRuleSpec[]; }
interface EntrySpec { source: number; out: string; auto?: boolean; }

function build(specs: FileSpec[], entries: EntrySpec[], codeSplit: boolean): linkerContext {
  const inputs: InputFile[] = specs.map((sp, si) => {
    const f = new InputFile();
    const s = new Source();
    s.KeyPath = new Path(); s.KeyPath.Text = sp.path; s.KeyPath.Namespace = "file";
    s.Contents = new TextEncoder().encode("");
    f.Source = s;
    f.SideEffects.Kind = sp.sideEffects ?? 0;
    const records: any[] = (sp.imports ?? []).map((im) => {
      const r: any = new js_ast.ImportRecord();
      r.Kind = im.kind;
      r.Path = new Path(); r.Path.Text = im.path ?? ""; r.Path.Namespace = "file";
      r.SourceIndex = im.source >= 0 ? im.source : undefined;
      return r;
    });
    if (sp.kind === "css") {
      const cr = new CSSRepr();
      (cr.AST as any).ImportRecords = records;
      (cr.AST as any).LayersPreImport = sp.layersPre ?? null;
      (cr.AST as any).LayersPostImport = sp.layersPost ?? null;
      (cr.AST as any).Rules = (sp.cssRules ?? []).map((rule) => {
        const rr = new css_ast.Rule();
        const at = new css_ast.RAtImport();
        at.ImportRecordIndex = rule.recIdx;
        at.ImportConditions = mkCond(rule.conditions);
        rr.Data = at;
        return rr;
      });
      f.Repr = cr;
    } else {
      const jr = new JSRepr();
      jr.AST.ModuleScope = new js_ast.Scope();
      jr.AST.ExportsRef = ref(si, 0);
      jr.AST.ImportRecords = records;
      jr.AST.Parts = (sp.parts ?? []).map((ps) => {
        const p = new js_ast.Part();
        p.CanBeRemovedIfUnused = !!ps.removable;
        p.ForceTreeShaking = !!ps.forceTree;
        p.ImportRecordIndices = ps.importRecs ?? [];
        p.SymbolUses = new Map();
        for (const d of ps.deps ?? []) { const dep = new js_ast.Dependency(); dep.SourceIndex = d[0]; dep.PartIndex = d[1]; p.Dependencies.push(dep); }
        return p;
      });
      if (sp.cssSource !== undefined && sp.cssSource >= 0) jr.CSSSourceIndex = ast.MakeIndex32(sp.cssSource);
      f.Repr = jr;
    }
    return f;
  });
  const eps = entries.map((e) => {
    const ep = new EntryPoint();
    ep.SourceIndex = e.source; ep.OutputPath = e.out; ep.OutputPathWasAutoGenerated = !!e.auto;
    return ep;
  });
  const reachable = specs.map((_, i) => i);
  const g = CloneLinkerGraph(inputs, reachable, eps, codeSplit);

  const c = new linkerContext();
  c.graph = g;
  c.fs = MockFS({}, MockUnix, "/");
  c.uniqueKeyPrefix = "TEST";
  c.options = {
    CodeSplitting: codeSplit, TreeShaking: true,
    OutputExtensionJS: ".js", OutputExtensionCSS: ".css",
    AbsOutputBase: "/project/src",
    EntryPathTemplate: [
      { Data: "./", Placeholder: config.PathPlaceholder.DirPlaceholder },
      { Data: "/", Placeholder: config.PathPlaceholder.NamePlaceholder },
    ],
    ChunkPathTemplate: [
      { Data: "./", Placeholder: config.PathPlaceholder.NamePlaceholder },
      { Data: "-", Placeholder: config.PathPlaceholder.HashPlaceholder },
    ],
  };
  c.treeShakingAndCodeSplitting();
  computeChunks(c);
  return c;
}

function dump(c: linkerContext): any[] {
  const out: any[] = [];
  const nbits = c.graph.EntryPoints().length;
  for (const ch of c.chunks) {
    const bits: number[] = [];
    for (let b = 0; b < nbits; b++) if (ch.entryBits.HasBit(b)) bits.push(b);
    const files = [...ch.filesWithPartsInChunk].sort((a, b) => a - b);
    const d: any = {
      key: ch.uniqueKey, bits, isEntry: ch.isEntryPoint, sourceIndex: ch.sourceIndex,
      entryBit: ch.entryPointBit, files, repr: ch.chunkRepr instanceof chunkReprJS ? "js" : "css",
      filesInOrder: [], partsInOrder: [], importsInOrder: [],
      hasCSS: false, cssChunkIndex: 0,
      tpl: ch.finalTemplate.map((p) => ({ data: p.Data, ph: p.Placeholder })),
      epChunk: c.graph.Files[ch.sourceIndex].EntryPointChunkIndex,
    };
    if (ch.chunkRepr instanceof chunkReprJS) {
      const r = ch.chunkRepr;
      d.filesInOrder = r.filesInChunkInOrder;
      d.partsInOrder = r.partsInChunkInOrder.map((pr) => ({ s: pr.sourceIndex, b: pr.partIndexBegin, e: pr.partIndexEnd }));
      d.hasCSS = r.hasCSSChunk; d.cssChunkIndex = r.cssChunkIndex;
    } else {
      const r = ch.chunkRepr as chunkReprCSS;
      d.importsInOrder = r.importsInChunkInOrder.map((io) => ({
        kind: io.kind, sourceIndex: io.kind === cssImportSourceIndex ? io.sourceIndex : 0,
        externalPath: io.kind === cssImportExternalPath ? io.externalPath.Text : "",
        layers: io.layers ?? [],
        conditions: io.conditions.map((cd) => ({
          layers: cd.Layers.map((t) => t.Text), supports: cd.Supports.map((t) => t.Text), queries: cd.Queries.length,
        })),
        condRecCount: io.conditionImportRecords.length,
      }));
    }
    out.push(d);
  }
  return out;
}

